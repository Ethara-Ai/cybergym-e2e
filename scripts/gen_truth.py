#!/usr/bin/env python3
"""Generate a grader-only TRUTH.md for a kakashi task from its own ground truth.

Mirrors the per-task ground-truth doc other harnesses ship, but shaped to this
harness's vuln/PoC/patch model. It is DERIVED deterministically from the task's
committed artifacts, so it can be regenerated and diffed:

  task.toml            -> vulnerability metadata (project, OSV/CVE, commits, target)
  solution/fix.patch   -> the reference fix (files touched, size)
  solution/poc.bin     -> reference PoC (size + sha256)
  tests/data/poc.bin   -> ground-truth PoC used in Stage 4 (size + sha256)
  tests/test_weights.json -> the weighted oracle (positive stages + cheat gates)
  tests/rubric.json    -> the judge criteria (the rubric answer key)

TRUTH.md is grader-only and is NOT read by the runner or shown to the agent, so
writing it never affects scoring or a run.

Usage:
    python3 scripts/gen_truth.py tasks/<task>            # write tasks/<task>/TRUTH.md
    python3 scripts/gen_truth.py tasks/<task> --stdout   # print, don't write
    python3 scripts/gen_truth.py --all                   # every task under tasks/
"""
import argparse
import hashlib
import json
import re
from pathlib import Path

try:
    import tomllib  # py3.11+
except ModuleNotFoundError:  # pragma: no cover
    tomllib = None


def _sha256(p: Path) -> str:
    try:
        return hashlib.sha256(p.read_bytes()).hexdigest()
    except Exception:
        return "(unreadable)"


def _load_toml(p: Path) -> dict:
    if tomllib is None or not p.exists():
        return {}
    try:
        return tomllib.loads(p.read_text())
    except Exception:
        return {}


def _patch_files(patch: Path) -> list[str]:
    if not patch.exists():
        return []
    files = []
    for line in patch.read_text(errors="replace").splitlines():
        m = re.match(r"^\+\+\+ b/(.+)$", line)
        if m and m.group(1) != "/dev/null":
            files.append(m.group(1))
    return files


def _poc_line(p: Path, label: str) -> str:
    if not p.exists():
        return f"- {label}: (missing)"
    return f"- {label}: `{p.name}` — {p.stat().st_size} bytes, sha256 `{_sha256(p)[:16]}…`"


def generate(task_dir: Path) -> str:
    task_dir = Path(task_dir)
    toml = _load_toml(task_dir / "task.toml")
    meta = toml.get("metadata", {}) or {}
    name = toml.get("name") or task_dir.name
    mode = toml.get("mode", "e2e")

    tests = task_dir / "tests"
    weights = {}
    try:
        weights = json.loads((tests / "test_weights.json").read_text())
    except Exception:
        pass
    positives = {k: v for k, v in weights.items() if v > 0}
    negatives = {k: v for k, v in weights.items() if v < 0}
    pos_total = sum(positives.values())

    rubric = []
    try:
        r = json.loads((tests / "rubric.json").read_text())
        rubric = r if isinstance(r, list) else r.get("criteria", r.get("rubric", []))
    except Exception:
        pass

    fix = task_dir / "solution" / "fix.patch"
    patch_files = _patch_files(fix)

    L = []
    L.append(f"# TRUTH.md — {name}")
    L.append("")
    L.append("Grader-only. Never shown to the agent under evaluation.")
    L.append("Auto-generated by `scripts/gen_truth.py` from this task's own ground-truth")
    L.append("artifacts (task.toml, solution/, tests/). Do not hand-edit — regenerate.")
    L.append("")

    # --- Vulnerability ---
    L.append("## Vulnerability")
    L.append("")
    for key, label in (("project", "Project"), ("osv_id", "OSV"), ("cve_id", "CVE"),
                       ("summary", "Summary"), ("fuzz_target", "Fuzz target"),
                       ("vulnerable_commit", "Vulnerable commit"), ("fixed_commit", "Fixed commit"),
                       ("repo_url", "Repo")):
        if meta.get(key):
            L.append(f"- **{label}:** {meta[key]}")
    L.append(f"- **Mode:** {mode}")
    if toml.get("description"):
        L.append(f"- **Task:** {toml['description']}")
    L.append("")

    # --- Reference solution ---
    L.append("## Reference solution (the answer key)")
    L.append("")
    L.append("### Proof-of-concept")
    L.append(_poc_line(tests / "data" / "poc.bin", "Ground-truth PoC (Stage 4)"))
    L.append(_poc_line(task_dir / "solution" / "poc.bin", "Reference PoC"))
    L.append("")
    L.append("### Fix")
    if fix.exists():
        nlines = len(fix.read_text(errors='replace').splitlines())
        L.append(f"- `solution/fix.patch` — {nlines} lines; touches: "
                 + (", ".join(f"`{f}`" for f in patch_files) or "(no files parsed)"))
    else:
        L.append("- (no solution/fix.patch)")
    L.append("")

    # --- Scoring ---
    L.append("## How it is scored")
    L.append("")
    L.append("`reward = (pytest_score + rubric_score) / 2`")
    L.append("")
    L.append("- **pytest_score** — weighted oracle (below): "
             "`Σ passed positive weights − Σ fired cheat-gate weights) / Σ positive weights`, clamped [-1, 1].")
    L.append("- **rubric_score** — an LLM judge grades the trajectory against the criteria below, "
             "run as 11 position-shuffled trials, median reported.")
    L.append(f"- **agent_success** (the pass@k \"solved\" bit) — all required stages pass.")
    L.append("")

    # oracle
    L.append(f"### Oracle — weighted tests (positive total = {pos_total})")
    L.append("")
    L.append("**Positive (must pass):**")
    for k, v in sorted(positives.items(), key=lambda kv: (-kv[1], kv[0])):
        L.append(f"- `{k}` (+{v})")
    L.append("")
    L.append("**Cheat gates (negative — must NOT fire; firing zeros gated credit):**")
    for k, v in sorted(negatives.items(), key=lambda kv: (kv[1], kv[0])):
        L.append(f"- `{k}` ({v})")
    L.append("")

    # rubric
    L.append(f"### Rubric — {len(rubric)} criteria (judge)")
    L.append("")
    for c in rubric:
        num = c.get("number") or c.get("id") or "?"
        sc = c.get("score", c.get("points", ""))
        is_pos = c.get("is_positive", True)
        try:
            score_str = f"{'+' if is_pos else '−'}{abs(int(sc))}"
        except Exception:
            score_str = str(sc)
        imp = c.get("importance", "")
        typ = c.get("type", "")
        crit = (c.get("criterion") or c.get("text") or "").strip()
        tag = " · ".join(t for t in (score_str, imp, typ) if t)
        L.append(f"- **{num}** [{tag}] {crit}")
    L.append("")
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser(description="Generate a grader-only TRUTH.md for a kakashi task")
    ap.add_argument("task_dir", nargs="?", help="tasks/<task>")
    ap.add_argument("--all", action="store_true", help="every task under tasks/")
    ap.add_argument("--stdout", action="store_true", help="print instead of writing TRUTH.md")
    args = ap.parse_args()

    root = Path(__file__).resolve().parent.parent
    if args.all:
        targets = [d for d in sorted((root / "tasks").iterdir()) if (d / "task.toml").exists()]
    elif args.task_dir:
        targets = [Path(args.task_dir)]
    else:
        ap.error("give a task_dir or --all")

    for t in targets:
        md = generate(t)
        if args.stdout:
            print(md)
        else:
            (t / "TRUTH.md").write_text(md, encoding="utf-8")
            print(f"  wrote {t / 'TRUTH.md'}")


if __name__ == "__main__":
    main()
